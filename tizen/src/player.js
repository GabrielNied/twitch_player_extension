// Player: the extension's ad filter and hls.js, Twitch chat over or beside
// the video, and an overlay (OK or ↑ / ↓) with the stream info, actions and a
// row of live channels to switch to. CH+/CH− switch channels directly.
import { fetchMaster, getStreamInfo, OfflineError, PRIMARY_PLAYER_TYPE } from '../../api.js';
import { AdFilter } from '../../ads.js';
import { realignOnLevelSwitch } from '../../realign.js';
import { $, h, streamCard, formatUptime, toast } from './ui.js';
import * as nav from './nav.js';
import { Chat } from './chat.js';
import { getSettings, setSetting, isFavorite, toggleFavorite } from './store.js';
import * as twitch from './twitch.js';

const OVERLAY_HIDE_MS = 8000;
const INFO_REFRESH_MS = 60_000;
const LIST_MAX_AGE = 60_000;
const RESYNC_AFTER = 30;   // s behind live after a pause before jumping to live
const KEEP_AWAKE_MS = 90_000; // under the TV's 2 minutes without input

const video = $('video');
const chat = new Chat($('chat-list'));

let onExit = null;
let login = null;
let info = {};
let hls = null;
let filter = null;
let startId = 0;
let restartTimer = 0;
let infoTimer = 0;
let overlayTimer = 0;
let lastKeyAt = 0;
let generatedUntil = 0;
let layer = null;          // null | 'osd' | 'menu'
let list = { title: '', streams: [], at: 0 };
let adMode = 'clean';
let suspended = false;

const ACTIONS = {
  chat() {
    const on = !getSettings().chat;
    setSetting('chat', on);
    applyChat();
    if (on) chat.join(login, getSettings());
    else chat.leave();
  },
  chatSide() {
    setSetting('chatSide', getSettings().chatSide === 'left' ? 'right' : 'left');
    applyChat();
  },
  chatMode() {
    setSetting('chatMode', getSettings().chatMode === 'side' ? 'overlay' : 'side');
    applyChat();
  },
  quality: openMenu,
  favorite() {
    toast(toggleFavorite(login) ? 'Adicionado aos favoritos' : 'Removido dos favoritos');
  },
  reload() {
    closeOverlay();
    start();
  },
};

export function init(exit) {
  onExit = exit;
  for (const button of $('osd-actions').querySelectorAll('[data-action]')) {
    button.addEventListener('click', () => {
      ACTIONS[button.dataset.action]();
      renderActions();
    });
  }
  video.addEventListener('playing', () => {
    $('message').hidden = true;
    holdScreenSaver(true);
  });
  video.addEventListener('pause', () => holdScreenSaver(false));
  setInterval(keepAwake, 10_000);
}

// With the chat beside the video the picture doesn't cover the screen, and the
// S90F then ignores setScreenSaver and brings the screen saver after 2 minutes
// without input. A key generated by the app counts as input and restarts that
// count; → does nothing in the player while no overlay is open.
function keepAwake() {
  const s = getSettings();
  if (!hls || video.paused || layer || !s.chat || s.chatMode !== 'side') return;
  if (Date.now() - lastKeyAt < KEEP_AWAKE_MS) return;
  try {
    generatedUntil = Date.now() + 1000;
    webapis.appcommon.generateKey('ArrowRight');
    lastKeyAt = Date.now();
  } catch {
    // Not on a Samsung TV.
  }
}

// Samsung asks apps to turn the screen saver off while a video plays.
function holdScreenSaver(hold) {
  try {
    const { appcommon } = webapis;
    const { SCREEN_SAVER_OFF, SCREEN_SAVER_ON } = appcommon.AppCommonScreenSaverState;
    appcommon.setScreenSaver(hold ? SCREEN_SAVER_OFF : SCREEN_SAVER_ON, () => {}, err => console.warn('[player] screen saver', err));
  } catch {
    // Not on a Samsung TV.
  }
}

export function open(channel, preview) {
  $('player').hidden = false;
  nav.setScope($('player'));
  document.activeElement?.blur?.();
  play(channel, preview);
  if (Date.now() - list.at > LIST_MAX_AGE) loadList();
}

export function close() {
  stop();
  chat.leave();
  clearInterval(infoTimer);
  closeOverlay();
  $('player').hidden = true;
  login = null;
}

function exit() {
  close();
  onExit();
}

function play(channel, preview) {
  login = channel;
  info = { displayName: channel, ...preview };
  renderInfo();
  applyChat();
  const settings = getSettings();
  if (settings.chat) chat.join(channel, settings);
  else chat.leave();
  start();
  clearInterval(infoTimer);
  infoTimer = setInterval(updateInfo, INFO_REFRESH_MS);
  updateInfo();
  markCurrent();
}

// The TV put another app in front: drop the stream, reconnect live on return.
export function suspend() {
  if ($('player').hidden || suspended) return;
  suspended = true;
  stop();
  chat.leave();
}

export function resume() {
  if (!suspended) return;
  suspended = false;
  if (!login) return;
  start();
  if (getSettings().chat) chat.join(login, getSettings());
}

/* ---------- Playback ---------- */

function stop() {
  startId++;
  holdScreenSaver(false);
  clearTimeout(restartTimer);
  filter?.destroy();
  filter = null;
  hls?.destroy();
  hls = null;
  video.removeAttribute('src');
  video.load();
  $('paused').hidden = true;
}

async function start() {
  stop();
  const id = startId;
  adMode = 'clean';
  showMessage('Conectando…', true);
  let master;
  try {
    master = await fetchMaster(login, PRIMARY_PLAYER_TYPE);
  } catch (err) {
    if (id !== startId) return;
    if (err instanceof OfflineError) {
      showMessage(`${info.displayName} está offline. Verificando de novo a cada 30 segundos.`);
      restartTimer = setTimeout(start, 30_000);
    } else {
      showMessage(`Não foi possível carregar a live (${err.message}). Tentando de novo…`, true);
      restartTimer = setTimeout(start, 5_000);
    }
    return;
  }
  if (id !== startId) return;

  const settings = getSettings();
  filter = new AdFilter(login, master.variants, setAdStatus);
  const masterUrl = URL.createObjectURL(new Blob([master.text], { type: 'application/vnd.apple.mpegurl' }));
  hls = new Hls({
    pLoader: filter.loaderFor(Hls),
    liveDurationInfinity: true,
    liveSyncDurationCount: settings.lowLatency ? 2 : 3,
    // No speeding up to catch up with the live edge: TVs often mute the
    // audio while playbackRate isn't 1, which cut the sound for the first
    // seconds of some lives. The delay comes from where playback starts.
    maxLiveSyncPlaybackRate: 1,
    backBufferLength: 30,
    abrEwmaDefaultEstimate: 6_000_000, // start auto quality around 1080p, not at the bottom
  });
  realignOnLevelSwitch(hls, Hls);
  let recoveries = 0;

  hls.on(Hls.Events.MANIFEST_PARSED, () => {
    URL.revokeObjectURL(masterUrl);
    const level = levelFor(settings.quality);
    if (level >= 0) hls.currentLevel = level;
    // Auto starts at the top: on the TV the picture keeps the resolution it
    // started with when hls.js switches up later.
    else hls.startLevel = levelFor('source');
    video.play().catch(() => {});
  });
  hls.on(Hls.Events.LEVEL_SWITCHED, () => {
    renderStats();
    renderActions();
  });
  hls.on(Hls.Events.ERROR, (_, data) => {
    if (!data.fatal) return;
    console.warn('[player] fatal hls error', data.type, data.details);
    if (data.type === Hls.ErrorTypes.MEDIA_ERROR && recoveries < 2) {
      if (recoveries++ === 1) hls.swapAudioCodec();
      hls.recoverMediaError();
      return;
    }
    showMessage('Conexão perdida. Reconectando…', true);
    restartTimer = setTimeout(start, 3_000);
  });

  hls.loadSource(masterUrl);
  hls.attachMedia(video);
}

// Index of the level for a quality setting ('auto', 'source' or a height);
// -1 leaves the choice to hls.js.
function levelFor(quality) {
  if (quality === 'auto' || !hls) return -1;
  const levels = hls.levels
    .map((level, index) => ({ level, index }))
    .filter(({ level }) => level.height > 0)
    .sort((a, b) => b.level.height - a.level.height || b.level.bitrate - a.level.bitrate);
  if (!levels.length) return -1;
  if (quality === 'source') return levels[0].index;
  return (levels.find(({ level }) => level.height <= quality) || levels[levels.length - 1]).index;
}

const levelName = level => `${level.height}p${level.frameRate >= 50 ? Math.round(level.frameRate) : ''}`;

function qualityLabel() {
  const level = hls?.levels[hls.currentLevel];
  if (!level) return '';
  return hls.autoLevelEnabled ? `Auto · ${levelName(level)}` : levelName(level);
}

function togglePause() {
  if (!hls) {
    start();
    return;
  }
  if (!video.paused) {
    video.pause();
    $('paused').hidden = false;
    return;
  }
  // Back to live after a long pause instead of playing old video.
  const live = hls.liveSyncPosition;
  if (live && live - video.currentTime > RESYNC_AFTER) video.currentTime = live;
  video.play().catch(() => {});
  $('paused').hidden = true;
}

function showMessage(text, spinner = false) {
  $('message-text').textContent = text;
  $('message').classList.toggle('static', !spinner);
  $('message').hidden = false;
}

function setAdStatus(status) {
  const was = adMode;
  adMode = status.mode;
  if (adMode !== 'clean' && was === 'clean') toast('Anúncio bloqueado');
  // Pre-roll with no clean backup yet: say why nothing is showing.
  if (adMode === 'waiting' && video.readyState < 3) showMessage('Anúncio bloqueado. A live começa em instantes…', true);
  renderStats();
}

/* ---------- Stream info ---------- */

async function updateInfo() {
  const channel = login;
  let user;
  try {
    user = await getStreamInfo(channel);
  } catch {
    return;
  }
  if (channel !== login || !user) return;
  info = {
    ...info,
    displayName: user.displayName || channel,
    avatar: user.profileImageURL,
    title: user.broadcastSettings?.title || '',
    game: user.broadcastSettings?.game?.displayName || '',
    viewers: user.stream?.viewersCount,
    startedAt: user.stream?.createdAt,
    rerun: user.stream?.type === 'rerun',
    live: Boolean(user.stream),
  };
  renderInfo();
}

function renderInfo() {
  const avatar = $('osd-avatar');
  if (info.avatar) avatar.src = info.avatar;
  avatar.style.visibility = info.avatar ? '' : 'hidden';
  $('osd-name').textContent = info.displayName || login;
  $('osd-game').textContent = info.game ? `jogando ${info.game}` : '';
  $('osd-title').textContent = info.title || '';
  renderStats();
}

function renderStats() {
  const live = info.live !== false && Boolean(info.startedAt);
  const badge = $('osd-live');
  badge.hidden = !live;
  badge.textContent = info.rerun ? 'REPRISE' : 'AO VIVO';
  badge.classList.toggle('rerun', Boolean(info.rerun));
  $('osd-uptime').textContent = live ? formatUptime(info.startedAt) : '';
  $('osd-viewers').textContent = live && info.viewers != null ? `${info.viewers.toLocaleString('pt-BR')} espectadores` : '';
  $('osd-quality').textContent = qualityLabel();
  $('osd-ad').textContent = adMode === 'clean' ? ''
    : adMode === 'backup' ? 'Anúncio bloqueado · stream reserva' : 'Anúncio bloqueado';
}

/* ---------- Chat ---------- */

function applyChat() {
  const s = getSettings();
  const player = $('player');
  player.classList.toggle('chat-off', !s.chat);
  player.classList.toggle('chat-left', s.chatSide === 'left');
  player.classList.toggle('chat-beside', s.chatMode === 'side');
  player.style.setProperty('--chat-width', `${s.chatWidth}px`);
  player.style.setProperty('--chat-font', `${s.chatFont}px`);
  player.style.setProperty('--chat-bg', String(s.chatOpacity));
}

/* ---------- Live channels ---------- */

// Followed/favorite channels that are live, or "Em alta" when there are none.
async function loadList() {
  list.at = Date.now();
  try {
    const { live } = await twitch.following();
    list = live.length
      ? { title: 'Seguindo ao vivo', streams: live, at: Date.now() }
      : { title: 'Em alta', streams: await twitch.topStreams(getSettings().language), at: Date.now() };
  } catch (err) {
    console.warn('[player] channel list', err);
  }
  renderRail();
}

function renderRail() {
  const rail = $('rail');
  const focused = rail.contains(document.activeElement) ? document.activeElement.dataset.key : null;
  $('rail-title').textContent = list.title;
  rail.replaceChildren(...list.streams.map(s => streamCard(s, () => {
    closeOverlay();
    if (s.login !== login) play(s.login, s);
  })));
  markCurrent();
  const again = focused && rail.querySelector(`[data-key="${CSS.escape(focused)}"]`);
  if (again) nav.focus(again);
}

function markCurrent() {
  for (const card of $('rail').children) card.classList.toggle('current', card.dataset.key === login);
}

function switchBy(step) {
  const { streams } = list;
  if (!streams.length) {
    toast('Nenhum canal na lista');
    return;
  }
  const index = streams.findIndex(s => s.login === login);
  const from = index >= 0 ? index : step > 0 ? -1 : 0;
  const next = streams[(from + step + streams.length) % streams.length];
  if (next.login === login) return;
  toast(next.displayName);
  play(next.login, next);
}

/* ---------- Overlay ---------- */

function renderActions() {
  const s = getSettings();
  const label = (action, text) => { $('osd-actions').querySelector(`[data-action="${action}"]`).textContent = text; };
  label('chat', s.chat ? 'Chat: ligado' : 'Chat: desligado');
  label('chatSide', s.chatSide === 'left' ? 'Chat à esquerda' : 'Chat à direita');
  label('chatMode', s.chatMode === 'side' ? 'Chat ao lado' : 'Chat sobre o vídeo');
  label('quality', `Qualidade: ${qualityLabel() || '—'}`);
  label('favorite', isFavorite(login) ? '★ Favorito' : '☆ Favoritar');
}

function openOverlay(onRail) {
  layer = 'osd';
  renderInfo();
  renderActions();
  $('osd').hidden = false;
  nav.setScope($('osd'));
  const railCard = $('rail').querySelector('.current') || nav.focusables($('rail'))[0];
  nav.focus(onRail && railCard ? railCard : $('osd-actions').querySelector('.focusable'));
  if (Date.now() - list.at > LIST_MAX_AGE) loadList();
  bump();
}

function closeOverlay() {
  layer = null;
  $('osd').hidden = true;
  $('menu').hidden = true;
  clearTimeout(overlayTimer);
  nav.setScope($('player'));
  if (document.activeElement && document.activeElement !== document.body) document.activeElement.blur();
}

// The overlay hides itself after a while without keys.
function bump() {
  clearTimeout(overlayTimer);
  if (layer) overlayTimer = setTimeout(closeOverlay, OVERLAY_HIDE_MS);
}

function openMenu() {
  if (!hls?.levels.length) {
    toast('Aguarde a live carregar');
    return;
  }
  layer = 'menu';
  const levels = hls.levels
    .map((level, index) => ({ level, index }))
    .filter(({ level }) => level.height > 0)
    .sort((a, b) => b.level.height - a.level.height || b.level.bitrate - a.level.bitrate);
  const items = [
    menuItem('Automática', -1, hls.autoLevelEnabled),
    ...levels.map(({ level, index }) => menuItem(levelName(level), index, !hls.autoLevelEnabled && hls.currentLevel === index)),
  ];
  $('menu-list').replaceChildren(...items);
  $('menu').hidden = false;
  nav.setScope($('menu'));
  nav.focus($('menu-list').querySelector('.selected') || items[0]);
}

function menuItem(label, index, selected) {
  return h('button', {
    className: `menu-item focusable${selected ? ' selected' : ''}`,
    onclick: () => {
      if (hls) {
        hls.currentLevel = index;
        setSetting('quality', index < 0 ? 'auto' : hls.levels[index].height);
      }
      closeMenu();
      renderActions();
    },
  }, label);
}

function closeMenu() {
  $('menu').hidden = true;
  layer = 'osd';
  nav.setScope($('osd'));
  nav.focus($('osd-actions').querySelector('[data-action="quality"]'));
}

/* ---------- Keys ---------- */

const DIRECTIONS = new Set(['left', 'right', 'up', 'down']);

export function onKey(key) {
  if (key === 'right' && Date.now() < generatedUntil) return true; // from keepAwake()
  lastKeyAt = Date.now();
  bump();
  switch (key) {
    case 'playPause': togglePause(); return true;
    case 'play': if (video.paused) togglePause(); return true;
    case 'pause': if (!video.paused) togglePause(); return true;
    case 'stop': exit(); return true;
    case 'chUp': switchBy(-1); return true;
    case 'chDown': switchBy(1); return true;
    default: break;
  }
  if (layer) {
    if (DIRECTIONS.has(key)) nav.move(key);
    else if (key === 'enter') document.activeElement?.click?.();
    else if (key === 'back') {
      if (layer === 'menu') closeMenu();
      else closeOverlay();
    }
    return true;
  }
  if (key === 'enter' || key === 'up') openOverlay(false);
  else if (key === 'down') openOverlay(true);
  else if (key === 'back') exit();
  return true;
}
